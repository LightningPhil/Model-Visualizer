import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { format } from 'prettier'

const root = fileURLToPath(new URL('../', import.meta.url))
type LockedPackage = { version?: string; license?: string; dev?: boolean }
const lock = JSON.parse(readFileSync(resolve(root, 'package-lock.json'), 'utf8')) as {
  packages: Record<string, LockedPackage>
}
const packages = Object.entries(lock.packages)
  .filter(([path]) => path)
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
const notices = [
  'Model Visualizer — third-party notices',
  'Generated by npm run licenses from package-lock.json and installed packages.',
  'Project code is MIT; third-party code and assets retain their own licenses.',
  'Source, rebuilding and replacement instructions: licenses/README.txt',
  '',
  readFileSync(resolve(root, 'LICENSE'), 'utf8').trim(),
  '',
  readFileSync(resolve(root, 'public/licenses/README.txt'), 'utf8').trim(),
]
for (const [path, entry] of packages) {
  if (!entry.license) throw new Error(`Missing license metadata: ${path}`)
  if (entry.dev) continue
  const pinnedSources: Record<string, string> = {
    'node_modules/libavoid-js': '0.5.0-beta.5',
    'node_modules/elkjs': '0.12.0',
  }
  if (path in pinnedSources && entry.version !== pinnedSources[path]) {
    throw new Error(
      `Update corresponding source archives/instructions for ${path}@${entry.version}`,
    )
  }
  const directory = resolve(root, path)
  const installed = JSON.parse(readFileSync(resolve(directory, 'package.json'), 'utf8'))
  if (installed.version !== entry.version)
    throw new Error(`Run npm ci: ${path} differs from lockfile`)
  const files = readdirSync(directory)
    .filter((name) => /^(licen[sc]e|copying|notice|ofl)([.-]|$)/i.test(name))
    .sort()
  if (!files.length) throw new Error(`Missing license text: ${path}`)
  const repository = installed.repository?.url ?? installed.repository ?? installed.homepage ?? ''
  notices.push(
    '',
    '='.repeat(72),
    `${installed.name}@${entry.version} — ${entry.license}`,
    `Source: ${repository}`,
    `Package: https://www.npmjs.com/package/${installed.name}/v/${entry.version}`,
  )
  for (const file of files) {
    notices.push('', `--- ${file} ---`, readFileSync(resolve(directory, file), 'utf8').trim())
  }
}
notices.push(
  '',
  '='.repeat(72),
  'Stories260K checkpoint and matching tokenizer — Andrej Karpathy — MIT',
  readFileSync(resolve(root, 'public/models/stories260k/README.txt'), 'utf8').trim(),
  readFileSync(resolve(root, 'public/models/stories260k/LICENSE'), 'utf8').trim(),
)
writeFileSync(resolve(root, 'public/THIRD_PARTY_NOTICES.txt'), notices.join('\n') + '\n')
const inventory = [
  '# Dependency license inventory',
  '',
  'Generated by `npm run licenses` from the complete lockfile, including optional platform packages.',
  'Runtime entries conservatively include transitive dependencies and type declarations; build/test tools are not shipped as application code.',
  'Full runtime copyright and license texts ship in [third-party notices](../public/THIRD_PARTY_NOTICES.txt).',
  'ELK is used under EPL-2.0. Lucide also includes MIT notices for Feather-derived icons.',
  'The project MIT license does not replace these licenses. See [source and replacement instructions](../public/licenses/README.txt).',
  '',
  '| Package | Version | License metadata | Use |',
  '| --- | --- | --- | --- |',
  ...packages.map(([path, entry]) => {
    const name = path.split('node_modules/').at(-1)!
    return `| [${name}](https://www.npmjs.com/package/${name}/v/${entry.version}) | ${entry.version} | ${entry.license} | ${entry.dev ? 'Build/test' : 'Runtime'} |`
  }),
  '',
  'Additional bundled asset: Stories260K weights and tokenizer by Andrej Karpathy, MIT; the original license is in `public/models/stories260k/LICENSE`.',
  '',
]
writeFileSync(
  resolve(root, 'docs/dependency-licenses.md'),
  await format(inventory.join('\n'), { parser: 'markdown' }),
)
console.log(`Recorded ${packages.length} locked packages and full runtime license texts.`)
